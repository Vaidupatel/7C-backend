/**
 * Fallback LMS interpolation helper when a specific single month is requested.
 */
export function getBuiltinLms(
  standard: GrowthStandard,
  measure: GrowthMeasure,
  sex: Sex,
  ageMonths: number,
): LmsParams {
  const dataset = CDC_REFERENCE_DATA[sex]?.[measure] || [];
  if (dataset.length === 0) {
    // Safety bias (Finding C8 & Clinical Rule 5): Never return confident garbage fallback
    throw new Error(
      `No growth reference data available for ${standard} ${measure} ${sex} at ${ageMonths} months (PENDING_DOCTOR_APPROVAL)`,
    );
  }

  // Exact or closest match
  if (ageMonths <= dataset[0].ageMonths) {
    return { l: dataset[0].l, m: dataset[0].m, s: dataset[0].s };
  }
  if (ageMonths >= dataset[dataset.length - 1].ageMonths) {
    const last = dataset[dataset.length - 1];
    return { l: last.l, m: last.m, s: last.s };
  }

  // Find surrounding points and linear interpolate
  for (let i = 0; i < dataset.length - 1; i++) {
    const p1 = dataset[i];
    const p2 = dataset[i + 1];
    if (ageMonths >= p1.ageMonths && ageMonths <= p2.ageMonths) {
      const frac = (ageMonths - p1.ageMonths) / (p2.ageMonths - p1.ageMonths);
      return {
        l: Math.round((p1.l + frac * (p2.l - p1.l)) * 10000) / 10000,
        m: Math.round((p1.m + frac * (p2.m - p1.m)) * 10000) / 10000,
        s: Math.round((p1.s + frac * (p2.s - p1.s)) * 10000) / 10000,
      };
    }
  }

  return { l: dataset[0].l, m: dataset[0].m, s: dataset[0].s };
}
